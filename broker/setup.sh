#!/usr/bin/env bash
# Writes broker/mosquitto.conf for this checkout, creates the broker<->API secret and a
# self-signed dev certificate (replace with Let's Encrypt, see deploy/TLS-for-broker.md).
# Re-running keeps the secret and certificate. Restart both iot-api and iot-broker afterwards.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT/broker"
mkdir -p certs "$ROOT/data/mosquitto"

[ -f broker-api-secret ] || { umask 077; openssl rand -hex 24 > broker-api-secret; }
SECRET=$(cat broker-api-secret)
[ -f certs/server.crt ] || {
  openssl req -x509 -newkey rsa:2048 -nodes -days 365 -subj "/CN=localhost" \
    -keyout certs/server.key -out certs/server.crt 2>/dev/null
  chmod 600 certs/server.key
}

( umask 077; cat > mosquitto.conf <<CONF
# Generated by broker/setup.sh. Contains the broker<->API secret; do not commit.
persistence true
persistence_location $ROOT/data/mosquitto/
log_dest stdout
log_type error
log_type warning
log_type notice
allow_anonymous false

# local plain MQTT + browser WebSocket (nginx puts TLS in front of 9001)
listener 1883 127.0.0.1
listener 9001 127.0.0.1
protocol websockets

# public TLS for devices
listener 8883 0.0.0.0
protocol mqtt
certfile $ROOT/broker/certs/server.crt
keyfile $ROOT/broker/certs/server.key

plugin $ROOT/vendor/go-auth-src/go-auth.so
auth_opt_backends http
auth_opt_http_host 127.0.0.1
auth_opt_http_port 3021
auth_opt_http_getuser_uri /broker/$SECRET/user
auth_opt_http_superuser_uri /broker/$SECRET/superuser
auth_opt_http_aclcheck_uri /broker/$SECRET/acl
auth_opt_http_method POST
auth_opt_http_params_mode json
auth_opt_http_response_mode status
auth_opt_cache true
auth_opt_cache_type go-cache
auth_opt_cache_reset true
auth_opt_auth_cache_seconds 30
auth_opt_acl_cache_seconds 30
CONF
)
chmod 600 mosquitto.conf
echo "wrote $ROOT/broker/mosquitto.conf"
